        /**
     * Validates the input and saves a new inspection into the array.
     * Shows an error message if five inspections have already been captured.
     */
    private void saveInspection() {
        // Stop if the array is already full
        if (inspectionCount >= MAX_INSPECTIONS) {
            JOptionPane.showMessageDialog(this, "Maximum inspection count reached!",
                    "Message", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        // Read the user's input and remove extra spaces
        String name = txtHospitalName.getText().trim();
        String location = txtHospitalLocation.getText().trim();

        // Make sure both text fields were filled in
        if (name.isEmpty() || location.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the hospital name and location.",
                    "Missing details", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // The selected index is 0-4, so adding 1 gives 1-5 years
        int years = cboYears.getSelectedIndex() + 1;

        // Store the inspection in the next free slot and move the counter on
        inspections[inspectionCount] = new HospitalInspection(name, location, years);
        inspectionCount++;

        JOptionPane.showMessageDialog(this, "Inspection " + inspectionCount + " of "
                + MAX_INSPECTIONS + " saved.", "Saved", JOptionPane.INFORMATION_MESSAGE);

        // Empty the text fields so the next inspection can be entered
        txtHospitalName.setText("");
        txtHospitalLocation.setText("");
        txtHospitalName.requestFocus();
    }

    /**
     * Prints every saved inspection from the array into the list box.
     */
    private void printInspections() {
        listModel.clear(); // remove old output so nothing is listed twice

        if (inspectionCount == 0) {
            listModel.addElement("No inspections have been saved yet.");
            return;
        }

        // Loop only through the slots that hold saved inspections
        for (int i = 0; i < inspectionCount; i++) {
            HospitalInspection inspection = inspections[i];
            listModel.addElement("Hospital Name: " + inspection.getHospitalName());
            listModel.addElement("Hospital Location: " + inspection.getHospitalLocation());
            listModel.addElement("Years Since Inspection: " + inspection.getYearsText());
            listModel.addElement("******************************");
        }
    }

    /**
     * Clears the text fields and list box and resets the combo box.
     * The saved inspections in the array are kept.
     */
    private void clearControls() {
        txtHospitalName.setText("");
        txtHospitalLocation.setText("");
        cboYears.setSelectedIndex(0);
        listModel.clear();
        txtHospitalName.requestFocus();
        java.util.Arrays.fill(inspections, null);
        inspectionCount = 0;
    }
    
