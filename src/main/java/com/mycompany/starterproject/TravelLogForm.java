    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed

        // Capture the selected values from the three combo boxes
        String startLocation = (String) cboStartLocation.getSelectedItem();
        String endLocation = (String) cboEndLocation.getSelectedItem();
        String travelBy = (String) cboTravelBy.getSelectedItem();

        // A user cannot travel to the same place they start from
        if (startLocation.equals(endLocation)) {
            JOptionPane.showMessageDialog(this, "Destinations cannot be the same!!!",
                    "Message", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        saveTrip(startLocation, endLocation, travelBy); // write the trip to the file
        loadTravelLog();                                // read the file back into the list box
    }//GEN-LAST:event_btnSubmitActionPerformed

        /**
     * Saves one trip as a new line at the end of the sequential file travel.txt.
     * The file is opened in append mode, so earlier trips are kept.
     */
    private void saveTrip(String startLocation, String endLocation, String travelBy) {
        // try-with-resources closes the file automatically, even if an error occurs
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(FILE_NAME, true))) {
            writer.write(startLocation + SEPARATOR + endLocation + SEPARATOR + travelBy);
            writer.newLine();
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Could not save to " + FILE_NAME + ": " + e.getMessage(),
                    "File error", JOptionPane.ERROR_MESSAGE);
        }
    }

    /**
     * Reads travel.txt from top to bottom and shows every trip in the list box.
     */
    private void loadTravelLog() {
        // Start with a clean list and the heading
        listModel.clear();
        listModel.addElement("TRAVEL LOG");
        listModel.addElement(STAR_LINE);

        // If nothing has been saved yet, the file does not exist
        File file = new File(FILE_NAME);
        if (!file.exists()) {
            listModel.addElement("No trips have been captured yet.");
            return;
        }

        try (BufferedReader reader = new BufferedReader(new FileReader(file))) {
            String line;
            // Read one line (one trip) at a time until the end of the file
            while ((line = reader.readLine()) != null) {
                // Split the line into start location, end location and travel type
                String[] parts = line.split(SEPARATOR);

                // Skip any damaged line that does not have exactly three values
                if (parts.length != 3) {
                    continue;
                }

                listModel.addElement("Destination 1: " + parts[0]);
                listModel.addElement("Destination 2: " + parts[1]);
                listModel.addElement("Travel By: " + parts[2]);
                listModel.addElement(STAR_LINE);
            }
        } catch (IOException e) {
            JOptionPane.showMessageDialog(this, "Could not read " + FILE_NAME + ": " + e.getMessage(),
                    "File error", JOptionPane.ERROR_MESSAGE);
        }
    }
